def get_resources(skill_name):
    if not isinstance(skill_name, str):
        return []

    key = skill_name.strip().lower()

    # Return copies to prevent accidental modification
    # of the original resource definitions.
    return [
        resource.copy()
        for resource in RESOURCES.get(key, [])
    ]
